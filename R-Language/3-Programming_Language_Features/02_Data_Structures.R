# DATA STRUCTURES (SEQUENCE TYPES)
#===============================================================================
# In computer science, a data structure is a way to organize, manage,
# and store data efficiently for access and modification.

# In R, common data structures include:

# 1. Vectors
# 2. Lists
# 3. Matrices
# 4. Arrays
# 5. Factors
# 6. Data Frames



#===============================================================================
# VECTORS
#===============================================================================
# A vector is a sequence of elements that share the same data type.

# Supported vector types:
# logical, integer, double (numeric), character, complex, raw


###############################################
# Creating Vectors
###############################################

# Using c()
x <- c(10,20,30,40,50)
x
class(x)
typeof(x)


# Using colon operator :
a <- 3:10
a

b <- 10:1
b

# Using variables
i <- 3
j <- 7
k <- i:j
k


###############################################
# rep() function
###############################################

rep(5,3)
rep("ab",6)

rep(c(1,2,3),5)
rep(c(1,2,3),each=5)


###############################################
# seq() function
###############################################

seq(1,10)
seq(1,10,by=0.5)

seq(0,20,2)
seq(11,1,-2)

seq(1,5,length=10)



#===============================================================================
# ATOMIC VECTOR TYPES
#===============================================================================

###############################################
# Numeric Vector
###############################################

a <- c(3.2,4.5,6.7)
class(a)


###############################################
# Integer Vector
###############################################

b <- 5L
class(b)

c <- as.integer(4)
class(c)


###############################################
# Character Vector
###############################################

x <- c("ganesh","babu","nishu")
class(x)


###############################################
# Logical Vector
###############################################

l <- c(TRUE,FALSE,TRUE)
class(l)



#===============================================================================
# VECTOR INDEXING
#===============================================================================

x <- c(10,20,30,40,50)

x[1]
x[3]
x[2:4]

# Negative indexing
x[-2]


###############################################
# Vector Filtering
###############################################

x[x>25]
x[x<40]
x[x==30]



###############################################
# which() function
###############################################

which(x>25)



###############################################
# any() and all()
###############################################

x <- c(1,3,5,7,9)

any(x>4)
all(x>0)



#===============================================================================
# VECTOR OPERATIONS
#===============================================================================

x <- c(2,4,6,8)
y <- c(10,20,30,40)

x+y
x-y
x*y
x/y



###############################################
# Basic Statistical Functions
###############################################

x <- c(2,4,6,8)

sum(x)
mean(x)
median(x)

sd(x)
var(x)

summary(x)



#===============================================================================
# LISTS
#===============================================================================
# Lists can store elements of different data types.

###############################################
# Creating Lists
###############################################

mylist <- list(1,2,"hello",TRUE)
mylist

class(mylist)


###############################################
# Named Lists
###############################################

employee <- list(
  name="Mark",
  age=40,
  salary=50000
)

employee$name



###############################################
# Accessing List Elements
###############################################

employee[[1]]
employee$name



###############################################
# Updating List
###############################################

employee$salary <- 60000
employee



#===============================================================================
# MATRICES
#===============================================================================
# A matrix is a 2D data structure with same data type.

###############################################
# Creating Matrix
###############################################

m <- matrix(1:9,nrow=3)
m

m <- matrix(1:9,nrow=3,byrow=TRUE)
m


###############################################
# Matrix Dimensions
###############################################

dim(m)
nrow(m)
ncol(m)



###############################################
# Matrix Indexing
###############################################

m[2,3]
m[1,]
m[,2]



###############################################
# Matrix Operations
###############################################

m1 <- matrix(1:9,nrow=3)
m2 <- matrix(10:18,nrow=3)

m1+m2
m1*m2

# Matrix multiplication
m1 %*% m2



#===============================================================================
# ARRAYS
#===============================================================================
# Arrays store data in more than two dimensions.

###############################################
# Creating Arrays
###############################################

v1 <- c(1,3,5)
v2 <- c(5,6,7,8,9,9)

arr <- array(c(v1,v2),dim=c(3,3,2))
arr


###############################################
# Array Indexing
###############################################

arr[1,2,1]
arr[2,1,2]



#===============================================================================
# FACTORS
#===============================================================================
# Factors represent categorical variables.

###############################################
# Creating Factors
###############################################

x <- c("male","female","male")

f <- factor(x)
f

levels(f)



###############################################
# Ordered Factors
###############################################

edu <- c(1,2,3,2,1)

f <- ordered(edu,
             labels=c("Elementary","Middle","High"))
f



#===============================================================================
# DATA FRAMES
#===============================================================================
# A data frame is a tabular data structure.

###############################################
# Creating Data Frame
###############################################

name <- c("John","Mark","Lisa")
salary <- c(2000,3000,4000)

df <- data.frame(name,salary)
df


###############################################
# Data Frame Structure
###############################################

str(df)
dim(df)
nrow(df)
ncol(df)


###############################################
# Accessing Data Frame
###############################################

df$name
df[1,]
df[,2]



###############################################
# Adding Column
###############################################

df$age <- c(25,30,35)
df



###############################################
# Filtering Data Frame
###############################################

df[df$salary>2500,]



###############################################
# Sorting Data Frame
###############################################

df[order(df$salary),]



#===============================================================================
# APPLY FAMILY FUNCTIONS
#===============================================================================
# Used for repetitive operations on data structures.

###############################################
# apply()
###############################################

X <- matrix(rnorm(30),5,6)
apply(X,2,sum)



###############################################
# lapply()
###############################################

MyList <- list(
  matrix(1:9,3,3),
  matrix(4:12,3,3)
)

lapply(MyList,mean)



###############################################
# sapply()
###############################################

sapply(MyList,mean)



###############################################
# vapply()
###############################################

vapply(1:5,sqrt,numeric(1))



###############################################
# tapply()
###############################################

salary <- c(1000,2000,1500,3000)

dept <- factor(c("IT","HR","IT","HR"))

tapply(salary,dept,mean)



###############################################
# mapply()
###############################################

mapply(sum,1:5,6:10)



