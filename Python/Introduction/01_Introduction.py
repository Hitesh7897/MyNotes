# ============================================================
# WHAT IS PYTHON?
# ============================================================

"""
Python is a high-level, interpreted, general-purpose programming language
that emphasizes code readability and simplicity.

It was specifically designed to be easy to learn and use, making it
an excellent choice for beginners as well as experienced developers.

Python follows a clean syntax that allows programmers to write fewer
lines of code compared to many other programming languages.

Python supports multiple programming paradigms:
    • Object-Oriented Programming (OOP)
    • Procedural Programming
    • Functional Programming (to some extent)

Python also provides automatic (dynamic) memory management,
which eliminates the need for manual memory allocation.
"""

# ============================================================
# HISTORY OF PYTHON
# ============================================================

"""
Python was created by Guido van Rossum at Centrum Wiskunde &
Informatica (CWI) in the Netherlands.

Development of Python began in the late 1980s, and the first
official version (Python 0.9.0) was released in February 1991.

The name "Python" was inspired by the British comedy television
series "Monty Python's Flying Circus" and not by the snake.
"""

