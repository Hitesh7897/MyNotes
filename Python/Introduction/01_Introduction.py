# ============================================================
# HOW PYTHON WORKS
# ============================================================

"""
Python is an interpreted language.

Unlike compiled languages such as C or C++, Python code is first
converted into bytecode (.pyc), which is then executed by the
Python Virtual Machine (PVM).

Flow:

Python Code (.py)
        ↓
Python Interpreter
        ↓
Bytecode (.pyc)
        ↓
Python Virtual Machine (PVM)
        ↓
Program Output
"""

# ============================================================
# KEY CHARACTERISTICS
# ============================================================

"""
✔ High-Level Language
    - Easy for humans to read and write.

✔ Interpreted
    - Executes code line by line.

✔ Dynamically Typed
    - Variable types are determined during runtime.

✔ Object-Oriented
    - Supports classes, objects, inheritance, polymorphism, etc.

✔ Portable
    - Code written once can run on multiple operating systems.

✔ Extensible
    - Can integrate with C, C++, Java, and other languages.

✔ Large Standard Library
    - Includes built-in modules for file handling, networking,
      databases, mathematics, regular expressions, and more.
"""

